import { webcrypto } from 'node:crypto';
import forge from 'node-forge';
import * as xadesjs from 'xadesjs';
import { DOMParser, XMLSerializer } from '@xmldom/xmldom';
import xpath from 'xpath';

xadesjs.Application.setEngine('NodeJS', webcrypto as any);
xadesjs.setNodeDependencies({ DOMParser, XMLSerializer, xpath });

/** Hacienda signature policy (XAdES-EPES). The digest is the SHA-256 of the policy PDF published on Hacienda's CDN. */
const POLICY_URL =
  'https://cdn.comprobanteselectronicos.go.cr/xml-schemas/Resoluci%C3%B3n_General_sobre_disposiciones_t%C3%A9cnicas_comprobantes_electr%C3%B3nicos_para_efectos_tributarios.pdf';
const POLICY_DIGEST = 'DWxin1xWOeI8OuWQXazh4VjLWAaCLAA954em7DMh0h8=';
const ALG = { name: 'RSASSA-PKCS1-v1_5', hash: 'SHA-256' };

export type SigningCert = { key: CryptoKey; certB64: string; subject: string; serialName: string | null; notBefore: Date; notAfter: Date };

/** Opens the "llave criptográfica" (.p12) downloaded from ATV. Throws on a wrong PIN. */
export async function loadP12(p12: Buffer, pin: string): Promise<SigningCert> {
  let p: forge.pkcs12.Pkcs12Pfx;
  try {
    p = forge.pkcs12.pkcs12FromAsn1(forge.asn1.fromDer(forge.util.createBuffer(p12.toString('binary'))), false, pin);
  } catch {
    throw new Error('No se pudo abrir la llave criptográfica: PIN incorrecto o archivo .p12 inválido');
  }
  const bag = (t: string) => p.getBags({ bagType: t })[t] || [];
  const keyBag = bag(forge.pki.oids.pkcs8ShroudedKeyBag)[0] || bag(forge.pki.oids.keyBag)[0];
  const priv = keyBag?.key as forge.pki.rsa.PrivateKey | undefined;
  if (!priv) throw new Error('La llave criptográfica no contiene una llave privada');
  const certs = bag(forge.pki.oids.certBag).map((b) => b.cert!).filter(Boolean);
  const cert = certs.find((c) => (c.publicKey as forge.pki.rsa.PublicKey).n.equals(priv.n)) || certs[0];
  if (!cert) throw new Error('La llave criptográfica no contiene un certificado');
  const pkcs8 = forge.asn1.toDer(forge.pki.wrapRsaPrivateKey(forge.pki.privateKeyToAsn1(priv))).getBytes();
  const key = await webcrypto.subtle.importKey('pkcs8', Buffer.from(pkcs8, 'binary'), ALG, false, ['sign']);
  return {
    key: key as unknown as CryptoKey,
    certB64: Buffer.from(forge.asn1.toDer(forge.pki.certificateToAsn1(cert)).getBytes(), 'binary').toString('base64'),
    subject: cert.subject.attributes.map((a) => `${a.shortName || a.name}=${a.value}`).join(', '),
    serialName: (cert.subject.getField({ type: '2.5.4.5' }) as any)?.value ?? null, // e.g. CPJ-3-101-123456
    notBefore: cert.validity.notBefore,
    notAfter: cert.validity.notAfter,
  };
}

let simCertP: Promise<SigningCert> | null = null;
/** Throw-away self-signed key used only in the Simulación environment when no .p12 has been uploaded. */
export function simulationCert(): Promise<SigningCert> {
  if (!simCertP) {
    simCertP = (async () => {
      const keys = forge.pki.rsa.generateKeyPair(2048);
      const cert = forge.pki.createCertificate();
      cert.publicKey = keys.publicKey; cert.serialNumber = '01';
      cert.validity.notBefore = new Date(Date.now() - 86400e3); cert.validity.notAfter = new Date(Date.now() + 10 * 365 * 86400e3);
      const attrs = [{ name: 'commonName', value: 'SIMULACION - SIN VALIDEZ FISCAL' }, { name: 'countryName', value: 'CR' }];
      cert.setSubject(attrs); cert.setIssuer(attrs); cert.sign(keys.privateKey, forge.md.sha256.create());
      const der = forge.asn1.toDer(forge.pkcs12.toPkcs12Asn1(keys.privateKey, [cert], 'sim', { algorithm: '3des' })).getBytes();
      return loadP12(Buffer.from(der, 'binary'), 'sim');
    })();
  }
  return simCertP;
}

/** Signs a comprobante with an enveloped XAdES-EPES signature (RSA-SHA256, inclusive C14N), as Hacienda requires. */
export async function signXml(xml: string, cert: SigningCert): Promise<string> {
  const doc = xadesjs.Parse(xml);
  const signed = new xadesjs.SignedXml();
  // The Signature Id is generated by xadesjs so QualifyingProperties/@Target always points at it.
  const sig = await signed.Sign(ALG, cert.key, doc, {
    canonicalization: 'c14n',
    references: [{ uri: '', hash: 'SHA-256', transforms: ['enveloped', 'c14n'] }],
    signedPropertiesReference: { hash: 'SHA-256', transforms: ['c14n'] },
    x509: [cert.certB64],
    signingCertificate: { certificate: cert.certB64, digestAlgorithm: 'SHA-256' },
    signingTime: { value: new Date() },
    policy: { hash: 'SHA-256', identifier: { value: POLICY_URL }, digestValue: POLICY_DIGEST },
  } as any);
  doc.documentElement.appendChild(sig.GetXml()!);
  return '<?xml version="1.0" encoding="utf-8"?>' + new XMLSerializer().serializeToString(doc as any).replace(/^<\?xml[^>]*\?>/, '');
}

/** Verifies the signature of a signed comprobante (used by tests and the connection check). */
export async function verifyXml(xml: string): Promise<boolean> {
  const doc = xadesjs.Parse(xml);
  const sigNode = doc.getElementsByTagNameNS('http://www.w3.org/2000/09/xmldsig#', 'Signature')[0];
  const s = new xadesjs.SignedXml(doc);
  s.LoadXml(sigNode as any);
  return s.Verify();
}
